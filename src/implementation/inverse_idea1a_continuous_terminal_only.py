"""Frozen-forward continuous-amplitude inversion, vectorized version.

Method 1
--------
The target terminal waveforms are generated by SSFM from true PAM4 amplitudes
{0.25, 0.5, 0.75, 1.0}.  During inversion the optimizer is deliberately NOT
told that four discrete levels exist: the frozen forward PINN only receives M
continuous trainable amplitudes constrained to [0,1].  Nearest-PAM4 rounding is
performed after optimization only for reporting exact-match accuracy.

Speed changes in this version
-----------------------------
* The four restarts of one sample are optimized in one tensor batch.
* With ``--batch-mode all_samples`` (or default ``auto``), all 10 samples x 4
  restarts are optimized together, i.e. one batch of 40 amplitude vectors.
* The 3000 epochs are now a maximum budget.  By default the run stops when 90%
  of restart trajectories have plateaued for the requested patience period.
* Every restart still keeps an independent best state and best epoch.
"""
