"""
Draw three compact waveform icons for insertion into a paper table.

Figure 1 (forward):
    actual input waveform (red)  ->  SSFM output waveform (blue)

Figure 2 (inverse, A_min = 0.05):
    predicted input waveform (blue)  <-  observed output waveform (red)
    The displayed input vector is manually constructed so that one tiny
    sub-pulse of amplitude 0.05 is placed near the center and its two
    neighboring pulses are intentionally larger, to visually emphasize
    the difficulty of recovering a very small pulse.

Figure 3 (inverse, A_min = 0.20):
    same as Figure 2, but the central small pulse is 0.20.

Notes
-----
- All "observed output waveforms" are generated by the project's real SSFM.
- For Figures 2 and 3, the displayed predicted-input waveform is intentionally
  constructed for illustration (rather than selected from the 200-sample pool),
  because the main goal is to visually explain the effect of A_min.
- Publication style matches the first universal-model K=8 waterfall figure:
      BLUE = #0000FF, lw = 1.10, alpha = 0.88
      RED  = #FF0000, lw = 0.95, alpha = 0.88
- Font: Times New Roman, 14 pt.
"""

